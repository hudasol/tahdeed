"""Render docs/EDGE_PROPOSAL.md: a two page note whose every number is read from a result file."""

import json
from pathlib import Path

R = Path(__file__).resolve().parents[1]
D = R / "docs"


def L(p):
    return json.loads((D / p).read_text(encoding="utf-8"))


def pc(x):
    return f"{100 * x:.1f}%"


def ci(d):
    lo, hi = (max(0.0, x) for x in d["ci95"])
    return f"{100 * d['rate']:.1f}% (95% interval {100 * lo:.1f} to {100 * hi:.1f})"


sealed = L("sealed/eval.json")
ccs = L("crosscity_sealed.json")
clar = L("clarify_dev.json")["groups"]["non_hole"]
pa = L("poi_ablation.json")["models"]
rss = L("region_rss.json")
lm = L("lastmeter_eval.json")
a, h = sealed["abu_dhabi_structured"], sealed["coverage_hole"]
base = ccs["configs"]["baseline_v2.0"]["cells"]["risk/E0"]["wrong_city_of_all"]
gate = ccs["configs"]["gate_0.35"]["cells"]["risk/E0"]["wrong_city_of_all"]
gate_std = ccs["configs"]["gate_0.35"]["standard"]["resolved_coverage"]
base_std = ccs["configs"]["baseline_v2.0"]["standard"]["resolved_coverage"]
m21, mno = pa["M21"], pa["M_nopoihole"]
lp = lm["proposers"]

out = f"""<!-- GENERATED by scripts/make_edge_proposal.py from docs/*.json; do not edit numbers by hand. -->
# Tahdeed: a proposal note for the Edge Group

Huda Mueen. Repository: <https://github.com/hudasol/tahdeed>. Every number below is read by a script
from a committed result file, named in brackets.

## Problem

An autonomous delivery robot or drone needs a point to stop at, not a postcode. In the UAE the
destination usually arrives as free text, in Arabic, English or both, and the official keys (Makani
in Dubai, Onwani in Abu Dhabi) are not open. A wrong answer given confidently, above all one in the
wrong city, costs more than a question to the customer. The task is therefore to resolve what can
be resolved, to say how sure the answer is, and to ask when it is not.

## What is built

- A bilingual resolver (Python, offline, no external API) that returns a point, a calibrated
  probability that the point is within 50 m, and an abstention with the missing field when unsure.
- A city gate: when a street or place name exists in several cities and no city is written, it asks
  "Which city?". The answer can be passed back (`city` in the API, CLI and dashboard).
- Gulf-AddressBench: versioned test sets with a scorer, baselines, a citation file and a CI job that
  fails if the committed results stop reproducing.
- An exploratory last meter module that proposes stopping points from open map geometry.

## Evidence

Held out districts, frozen v2.0 release, run once [sealed/eval.json]: {pc(a["resolved_coverage"])} of
Abu Dhabi emirate queries answered confidently; {pc(a["resolved_precision_50m"])} of those within 50 m;
calibration error (ECE) {a["ece_p50"]:.3f}. When the true address is missing from the map, precision
of confident answers falls to {pc(h["resolved_precision_50m"])}: a missing record yields a confident
neighbour, which only an official registry fixes.

Wrong city exposure on the synthetic cross city risk set, sealed, run once [crosscity_sealed.json]:
{ci(base)} without the gate, {ci(gate)} with it. The price is coverage: the standard benchmark's
confident share falls from {pc(base_std)} to {pc(gate_std)}.

Answering the question works [clarify_dev.json, dev split]: of {clar["asked_city"]["k"]} queries that
were asked "Which city?", {ci(clar["hint_resolved_within50"])} resolve within 50 m once the true city
is supplied, and {clar["hint_resolved_beyond50"]["k"]} resolve more than 50 m away.

A known trade off, diagnosed but not fixed [poi_ablation.json, dev, retrained on the 2026-10-15
extract]: Dubai POI calibration error is {m21["poi"]["shipped"]["ece_p50"]:.3f} in v2.1. Removing the
training rows that cause it brings it to {mno["poi"]["shipped"]["ece_p50"]:.3f}, but raises wrong city
exposure on the address risk set from
{pc(m21["crosscity"]["gate_0.35"]["risk_E0"]["wrong_city_of_all"]["rate"])} to
{pc(mno["crosscity"]["gate_0.35"]["risk_E0"]["wrong_city_of_all"]["rate"])}, so it was kept.

A demonstration fits a free 512 MB instance: the Abu Dhabi emirate build peaks at
{rss["after_queries_mb"]["VmHWM"]} MB resident [region_rss.json]. It has not been deployed.

Exploratory, last meter [lastmeter_eval.json]: on {lm["n_labelled_buildings"]} Abu Dhabi buildings with
entrances mapped in OpenStreetMap, the end of a footway at the outline lies within 10 m of a mapped
entrance for {ci(lp["path_endpoint"]["within_10m_of_all"])}, but partly because mappers join footways
to the entrance itself; the outline point facing the nearest road manages
{pc(lp["outline_nearest_road"]["within_10m_of_all"]["rate"])}, worse than the building centroid
({pc(lp["centroid"]["within_10m_of_all"]["rate"])}). Labels are OSM derived, not surveyed.

## Honest limits

- Every query in every benchmark is synthetic except 40 hand written ones. No real user query has
  been evaluated; absolute numbers are optimistic.
- Truth is OpenStreetMap, not an official register. Dubai has few structured addresses in OSM and
  is evaluated only on named places.
- No unused held out data remains: the v2.1 model has dev numbers only (docs/SEALED2.md).
- Training variance is not measured (one seed per model), and the original map snapshot could not
  be recovered, so the T1 diagnosis ran on a newer extract.
- The last meter results are exploratory, on mapped entrances only, with a leakage caveat.

## Next three funded steps

1. **Human written test set.** Collect 1,000 or more addresses as couriers and customers write them
   (kit in `bench/human_kit/`), held back as the next sealed set. It replaces the synthetic numbers
   above with real ones and is the only realistic source of fresh held out data.
2. **Official registry adapter.** With a written licence from Dubai Municipality (Makani; draft
   request in `docs/outreach/`) or Abu Dhabi (Onwani), wire the existing `RegistryAdapter` interface
   to a lookup and evaluate against the official entrance points. This removes the missing record
   failure and makes Dubai measurable.
3. **Last meter pilot.** Survey entrances and drop off points for a few hundred buildings in one
   district with an Edge delivery platform, then measure how far each proposal lands from where a
   robot or drone can actually stop.
"""
(D / "EDGE_PROPOSAL.md").write_text(out, encoding="utf-8")
print(len(out.split()), "words")
